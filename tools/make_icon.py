"""Builds the Numerone launcher icon: an hourglass whose sand is serif digits.

Writes the adaptive-icon foreground vector (108x108 viewport) and a PNG preview.
Usage (from the repo root):
  python tools/make_icon.py app/src/main/res/font/libre_caslon_text.ttf
      app/src/main/res/drawable/ic_launcher_foreground.xml icon_preview.png
"""
import math
import sys

from fontTools.misc.transform import Transform
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

INK = "#2A2623"
BEIGE = "#EDE6D9"

font_path, out_xml, out_png = sys.argv[1:4]
font = TTFont(font_path)
if "fvar" in font:
    font = instancer.instantiateVariableFont(font, {"wght": 700})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm


def digit(ch, cx, cy, size, angle):
    """Records glyph `ch` (em `size`) with its ink box centered on (cx, cy), turned `angle` degrees clockwise."""
    g = glyphs[cmap[ord(ch)]]
    bounds = BoundsPen(glyphs)
    g.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    s = size / upm
    # Applied right to left: center the glyph on the origin, flip y (font y-up -> drawable y-down), rotate, place.
    t = Transform().translate(cx, cy).rotate(math.radians(angle)).scale(s, -s).translate(-(x0 + x1) / 2, -(y0 + y1) / 2)
    pen = RecordingPen()
    g.draw(TransformPen(pen, t))
    return pen.value


def to_d(ops):
    out = []
    for op, pts in ops:
        if op == "moveTo":
            out.append("M%.2f,%.2f" % pts[0])
        elif op == "lineTo":
            out.append("L%.2f,%.2f" % pts[0])
        elif op == "qCurveTo":
            # TrueType implied on-curve points between consecutive off-curve points.
            *offs, end = pts
            for i, c in enumerate(offs):
                nxt = end if i == len(offs) - 1 else ((c[0] + offs[i + 1][0]) / 2, (c[1] + offs[i + 1][1]) / 2)
                out.append("Q%.2f,%.2f %.2f,%.2f" % (*c, *nxt))
        elif op == "curveTo":
            out.append("C" + " ".join("%.2f,%.2f" % p for p in pts))
        elif op == "closePath":
            out.append("Z")
    return "".join(out)


# --- Geometry (108x108; keep everything inside the r=33 safe circle around 54,54) ---
glass = [  # stroked outline of the two bulbs meeting at the neck
    "M38,31 C38,45 51.6,47.5 51.8,54 C51.6,60.5 38,63 38,77",
    "M70,31 C70,45 56.4,47.5 56.2,54 C56.4,60.5 70,63 70,77",
]
caps = ["M35.5,27.5 h37 a1.5,1.5 0 0 1 0,3 h-37 a1.5,1.5 0 0 1 0,-3 Z",
        "M35.5,77.5 h37 a1.5,1.5 0 0 1 0,3 h-37 a1.5,1.5 0 0 1 0,-3 Z"]

# Sand made of digits of pi (3.14159265358...), read from the top down, each one tilted as if tumbling:
# settled but askew in the top bulb, spinning through the neck, piled up at the bottom.
sand = [  # (digit, center x, center y, size, degrees clockwise, alpha)
    ("3", 45.6, 37.6, 8.4, -8, 1.0),
    ("1", 51.4, 37.4, 8.4, 7, 1.0),
    ("4", 57.0, 37.8, 8.4, -5, 1.0),
    ("1", 62.6, 37.4, 8.4, 11, 1.0),
    ("5", 50.8, 44.6, 7.2, 14, 1.0),
    ("9", 57.0, 44.4, 7.2, -12, 1.0),
    ("2", 54.0, 57.6, 4.4, 28, 0.85),
    ("6", 54.3, 62.4, 3.6, -34, 0.6),
    ("5", 55.2, 66.6, 7.0, -17, 1.0),
    ("3", 44.8, 73.2, 8.4, 10, 1.0),
    ("5", 50.9, 72.4, 8.4, -13, 1.0),
    ("8", 57.1, 72.8, 8.4, 6, 1.0),
    ("9", 63.2, 73.4, 8.4, -9, 1.0),
]
numbers = [(to_d(digit(ch, x, y, size, angle)), alpha) for ch, x, y, size, angle, alpha in sand]

# --- Vector drawable ---
xml = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- Generated by make_icon.py: hourglass with serif digits as sand. -->',
       '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
       '    android:width="108dp" android:height="108dp"',
       '    android:viewportWidth="108" android:viewportHeight="108">']
for d in glass:
    xml.append(f'    <path android:pathData="{d}" android:strokeColor="{INK}" android:strokeWidth="1.8" '
               'android:strokeLineCap="round" android:fillColor="#00000000" />')
for d in caps:
    xml.append(f'    <path android:pathData="{d}" android:fillColor="{INK}" />')
for d, alpha in numbers:
    xml.append(f'    <path android:pathData="{d}" android:fillColor="{INK}" android:fillAlpha="{alpha}" />')
xml.append("</vector>")
open(out_xml, "w", encoding="utf-8", newline="\n").write("\n".join(xml) + "\n")

# --- Preview (matplotlib), with a circular launcher mask ---
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Circle, PathPatch
from matplotlib.path import Path
import re


def mpl_path(d):
    """Minimal SVG path parser for the commands used above (M L C Q Z h a)."""
    toks = re.findall(r"[MLCQZhaz]|-?\d*\.?\d+", d)
    verts, codes, i, cur, start = [], [], 0, (0, 0), (0, 0)
    num = lambda: float(toks[i])
    while i < len(toks):
        c = toks[i]; i += 1
        if c == "M":
            cur = start = (float(toks[i]), float(toks[i + 1])); i += 2
            verts.append(cur); codes.append(Path.MOVETO)
        elif c == "L":
            cur = (float(toks[i]), float(toks[i + 1])); i += 2
            verts.append(cur); codes.append(Path.LINETO)
        elif c == "C":
            pts = [(float(toks[i + k]), float(toks[i + k + 1])) for k in (0, 2, 4)]; i += 6
            verts += pts; codes += [Path.CURVE4] * 3; cur = pts[-1]
        elif c == "Q":
            pts = [(float(toks[i + k]), float(toks[i + k + 1])) for k in (0, 2)]; i += 4
            verts += pts; codes += [Path.CURVE3] * 2; cur = pts[-1]
        elif c == "h":
            cur = (cur[0] + float(toks[i]), cur[1]); i += 1
            verts.append(cur); codes.append(Path.LINETO)
        elif c == "a":  # only used for the tiny cap ends: approximate with a line
            cur = (cur[0] + float(toks[i + 5]), cur[1] + float(toks[i + 6])); i += 7
            verts.append(cur); codes.append(Path.LINETO)
        elif c in "Zz":
            verts.append(start); codes.append(Path.CLOSEPOLY)
    return Path(verts, codes)


fig = plt.figure(figsize=(4, 4), dpi=120)
ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, 108); ax.set_ylim(108, 0); ax.axis("off")
fig.patch.set_facecolor("white")
ax.add_patch(Circle((54, 54), 54, color=BEIGE))
lw = 1.8 * 4 * 120 / 108 * 72 / 120  # 1.8 viewport units in points
for d in glass:
    ax.add_patch(PathPatch(mpl_path(d), fill=False, ec=INK, lw=lw, capstyle="round"))
for d in caps:
    ax.add_patch(PathPatch(mpl_path(d), fc=INK, ec="none"))
for d, alpha in numbers:
    ax.add_patch(PathPatch(mpl_path(d), fc=INK, ec="none", alpha=alpha))
ax.add_patch(Circle((54, 54), 33, fill=False, ec="#d33", lw=0.5, ls="--"))  # safe zone guide
fig.savefig(out_png)
print("ok")
